CREATE TABLE Direccion (
    Identificador NUMBER(12) GENERATED BY DEFAULT AS IDENTITY, 
    Numero NUMBER(5) NOT NULL,-- puse 5 por si acaso
    Calle VARCHAR (50) NOT NULL,
    Ciudad VARCHAR (50) NOT NULL,
    Pais VARCHAR (50) NOT NULL,
    PRIMARY KEY (Identificador)
);

--Categoria(id, nombre, descripcion)

CREATE TABLE Categoria (
    Identificador NUMBER(3) GENERATED BY DEFAULT AS IDENTITY, --GENERATED BY DEFAULT AS IDENTITY /
    Nombre VARCHAR(40) NOT NULL,
    Descripcion VARCHAR(200) NOT NULL,
    PRIMARY KEY (Identificador)
);
--Lugar( id, estado, nombre, longitud, latitud, direccion, categoria_principal)
    
CREATE TABLE Lugar (
    Identificador NUMBER(12) GENERATED BY DEFAULT AS IDENTITY,
    Estado CHAR(2) NOT NULL CHECK(Estado in ('OP','CT','CD')),
    Nombre VARCHAR(100) NOT NULL,
    Longitud NUMBER(7,4) NOT NULL CHECK (Longitud BETWEEN -180 AND 180),--Longitud va de -180 a 180 // 7 en total y 4 numeros de coma
    Latitud NUMBER(6,4) NOT NULL CHECK (Latitud BETWEEN -90 AND 90),--Latitud va de -90 a 90 // pongo cuatro descimales, porque los grados decimales son 4 digitos despues de la coma, normalmente
    Direccion NUMBER(12) NOT NULL,
    Categoria_principal NUMBER(3) NOT NULL,
    PRIMARY KEY (Identificador),
    FOREIGN KEY (Direccion) REFERENCES Direccion (Identificador),
    FOREIGN KEY (Categoria_principal) REFERENCES Categoria (Identificador)
);
--Sitioweb(idlugar, sitio)
    
CREATE TABLE SitioWeb (
    IdLugar NUMBER(12),
    Sitio VARCHAR(150),
    PRIMARY KEY (IdLugar, Sitio),
    FOREIGN KEY (IdLugar) REFERENCES Lugar (Identificador)
);
--Telefono_Lugar(idlugar, numero)
CREATE TABLE Telefono_Lugar (
    IdLugar NUMBER(12),
    Numero NUMBER(12), 
    PRIMARY KEY(Numero, IdLugar),
    FOREIGN KEY(IdLugar) REFERENCES Lugar(Identificador)
);
--Categoria_Secundaria(categoria, lugar)
CREATE TABLE Categoria_Secundaria(
    IdCategoria NUMBER(3),
    IdLugar NUMBER(12),
    PRIMARY KEY (IdCategoria, IdLugar),
    FOREIGN KEY (IdCategoria) REFERENCES Categoria (Identificador),
    FOREIGN KEY(IdLugar) REFERENCES Lugar(Identificador)
);
--Contenido(es_contenido, contenedor)
CREATE TABLE Contenido (
    Es_Contenido NUMBER(12),
    Contenedor NUMBER(12) NOT NULL, --no puede contenerse a si mismo
    PRIMARY KEY (Es_Contenido), 
    FOREIGN KEY (Es_Contenido) REFERENCES Lugar(Identificador),
    FOREIGN KEY (Contenedor) REFERENCES Lugar(Identificador),
    CONSTRAINT chk_contenido_no_contiene CHECK (Es_Contenido <> Contenedor)
);
--Horario(lugar, dia_semana, hora_cierre, hora_apertura)
CREATE TABLE Horario (
    IdLugar NUMBER(12),
    Dia_Semana CHAR(1) NOT NULL CHECK(Dia_Semana in ('L','M','X', 'J', 'V', 'S', 'D')),
    Hora_cierre NUMBER (2,0) CHECK(Hora_cierre BETWEEN 0 and 24), --2 numeros enteros, sin decimales// que pasa si quiere cerrar a las 17:30?
    Hora_apertura NUMBER (2,0) CHECK(Hora_apertura BETWEEN 0 and 24),
    PRIMARY KEY (IdLugar, Dia_Semana),
    FOREIGN KEY(IdLugar) REFERENCES Lugar(Identificador),
    CONSTRAINT chk_cierre_despues_apertura CHECK (Hora_cierre > Hora_apertura)
);

--Cuenta(correo_electronico, pais_residencial, nombre, idioma_preferido, estado, fecha_creacion)
CREATE TABLE Cuenta(
    Correo_Electronico VARCHAR(80), 
    Pais_Residencial VARCHAR(56) NOT NULL, --el país con el nombre más grande es Reino Unido de Gran Bretaña e Irlanda del Norte con 45 caracteres o 56 en inglés
    Nombre VARCHAR(50) NOT NULL, 
    Idioma_Preferido VARCHAR(35) NOT NULL, 
    Estado CHAR(1) NOT NULL CHECK(Estado IN ('A', 'S')), --A= Activo // S= Suspendido
    Fecha_Creacion DATE DEFAULT SYSDATE NOT NULL, --se coloca la fecha actual del sistema 
    PRIMARY KEY(Correo_Electronico)
);
--Telefono_Cuenta(cuenta, numero)
CREATE TABLE Telefono_Cuenta(
    IdCuenta VARCHAR(80),
    Numero NUMBER(12),
    PRIMARY KEY(IdCuenta, Numero),
    FOREIGN KEY(IdCuenta) REFERENCES Cuenta(Correo_Electronico)
);
--Guia_Local(cuenta, fecha_ingreso)
CREATE TABLE Guia_Local(
    IdCuenta VARCHAR(80),
    Fecha_Ingreso DATE DEFAULT SYSDATE NOT NULL, --se coloca la fecha actual del sistema
    PRIMARY KEY(IdCuenta),
    FOREIGN KEY(IdCuenta) REFERENCES Cuenta(Correo_Electronico)
);
--Propietario(cuenta, fecha_verificacion_titulo, metodo_verificacion, rut, razon_social)
CREATE TABLE Propietario(
    IdCuenta VARCHAR(80),
    Fecha_Verificacion_Titulo DATE DEFAULT SYSDATE NOT NULL, --se coloca la fecha actual del sistema
    Metodo_Verificacion CHAR(1) NOT NULL CHECK(metodo_verificacion in ('P','T','V')), -- "P" (Postal), "T" (Telefónico), "V" (Video)
    RUT NUMBER(15) NOT NULL,
    Razon_Social VARCHAR(20) UNIQUE NOT NULL, --AK
    PRIMARY KEY(IdCuenta),
    FOREIGN KEY(IdCuenta) REFERENCES Cuenta(Correo_Electronico)
);
--Es_Dueño(propietario, lugar, fecha_comienzo, fecha_fin)

CREATE TABLE Es_Duenio(
    IdPropietario VARCHAR(80), 
    IdLugar NUMBER(12), 
    Fecha_Comienzo DATE DEFAULT SYSDATE NOT NULL, --al crearlo, en ese momento comienza a ser dueño
    Fecha_Fin DATE, --Solo al cerrar el lugar o intercambiar de duenio??
    PRIMARY KEY(IdPropietario, IdLugar, Fecha_Comienzo),
    FOREIGN KEY(IdLugar) REFERENCES Lugar(Identificador),
    FOREIGN KEY(IdPropietario) REFERENCES Propietario(IdCuenta)
);
--Fotografia(id, lugar, fecha_subida, fecha_tomada, descripcion)
CREATE TABLE Fotografia(
    Identificador NUMBER(12) GENERATED BY DEFAULT AS IDENTITY, 
    IdLugar NUMBER(12), 
    Fecha_Subida DATE DEFAULT SYSDATE NOT NULL, 
    Fecha_Tomada DATE NOT NULL, 
    Descripcion VARCHAR(200), 
    PRIMARY KEY(Identificador, IdLugar),
    FOREIGN KEY(IdLugar) REFERENCES Lugar(Identificador)
);

--Subida_Por(lugar, id, cuenta) 
	
CREATE TABLE Subida_Por(
    IdFotografia NUMBER(12), 
    IdLugar NUMBER(12), 
    IdCuenta VARCHAR(80), --por si se borra una cuenta
    PRIMARY KEY(IdFotografia, IdLugar),
    FOREIGN KEY(IdFotografia, IdLugar) REFERENCES Fotografia(Identificador, IdLugar),
    FOREIGN KEY(IdCuenta) REFERENCES Cuenta(Correo_Electronico) ON DELETE SET NULL
);

--Reseña(id, texto, puntaje, idioma, fecha_subida, lugar, cuenta)

CREATE TABLE Resenia(
    Identificador NUMBER(12) GENERATED BY DEFAULT AS IDENTITY,
    Texto VARCHAR(100) NOT NULL,
    Puntaje NUMBER(1) NOT NULL CHECK((Puntaje BETWEEN 1 AND 5)),
    Idioma VARCHAR(35) NOT NULL,
    Fecha_Subida DATE DEFAULT SYSDATE NOT NULL,
    IdLugar NUMBER(12) NOT NULL,
    IdCuenta VARCHAR(80) NOT NULL,
    PRIMARY KEY(Identificador), --al ser unique, no hace falta poner el lugar y la cuenta en la PK
    FOREIGN KEY(IdLugar) REFERENCES Lugar(Identificador),
    FOREIGN KEY(IdCuenta) REFERENCES Cuenta(Correo_Electronico),
    CONSTRAINT UQ_Resena_Lugar_Cuenta UNIQUE (IdLugar, IdCuenta) --una cuenta solo puede hacer una reseña por lugar
);

--LeGusta(cuenta, resenia, fecha)
    CREATE TABLE LeGusta(
    IdCuenta VARCHAR(80),
    IdResenia NUMBER(12),
    Fecha DATE DEFAULT SYSDATE NOT NULL,
    PRIMARY KEY (IdCuenta, IdResenia),
    FOREIGN KEY (IdCuenta) REFERENCES Cuenta(Correo_Electronico),
    FOREIGN KEY (IdResenia) REFERENCES Resenia(Identificador)
);
--Respuesta(id, texto, fecha_publicacion, resenia)
	
CREATE TABLE Respuesta(
    Identificador NUMBER(12) GENERATED BY DEFAULT AS IDENTITY,
    Texto VARCHAR(100) NOT NULL,
    Fecha_Publicacion DATE DEFAULT SYSDATE NOT NULL,
    IdResenia NUMBER(12) NOT NULL,    
    PRIMARY KEY (Identificador),
    FOREIGN KEY (IdResenia) REFERENCES Resenia(Identificador)
);
--Dada_Por(respuesta, propietario)
CREATE TABLE Dada_Por(
    IdRespuesta NUMBER(12),
    IdPropietario VARCHAR(80) NOT NULL,    
    PRIMARY KEY (IdRespuesta),
    FOREIGN KEY (IdRespuesta) REFERENCES Respuesta(Identificador),
    FOREIGN KEY (IdPropietario) REFERENCES Propietario(IdCuenta) 
);
