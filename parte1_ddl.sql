    FOREIGN KEY(IdFotografia) REFERENCES Fotografia(Identificador, IdLugar),
    FOREIGN KEY(IdCuenta) REFERENCES Cuenta(Correo_Electronico) --esto tambien, no tendria que llamarlo, para que se sepa? o en cuenta
