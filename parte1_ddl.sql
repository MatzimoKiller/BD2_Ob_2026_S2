--Una cuenta no puede reseñar un mismo lugar dos veces, se remplaza con la nueva--|> -R53
--==============================================================================--|

CREATE OR REPLACE VIEW Resenia_Publicar AS
SELECT Texto, Puntaje, Idioma, Fecha_Subida, IdLugar, IdCuenta
FROM Resenia; -- creamos lo que vamos a usar despues para el trigger, en el trigger tiene el idCuenta

CREATE OR REPLACE TRIGGER trg_resenia_reemplazar
INSTEAD OF INSERT ON Resenia_Publicar
FOR EACH ROW
BEGIN
    -- Intenta reemplazar la reseña anterior de esa cuenta en ese lugar
    -- Y se sabe que se va a editar en la tabla Resenia, ya que va a por la vista que se hizo antes
    UPDATE Resenia
        SET Texto = :NEW.Texto,
            Puntaje = :NEW.Puntaje,
            Idioma = :NEW.Idioma,
            Fecha_Subida = SYSDATE
        WHERE IdLugar  = :NEW.IdLugar
            AND IdCuenta = :NEW.IdCuenta;

    -- Se ve que exista una reseña previa de esa cuenta en ese lugar
    IF SQL%ROWCOUNT = 0 THEN -- Acá vemos si no existe, si es el caso, lo creamos
        INSERT INTO Resenia (Texto, Puntaje, Idioma, Fecha_Subida, IdLugar, IdCuenta)
        VALUES (:NEW.Texto, :NEW.Puntaje, :NEW.Idioma, SYSDATE, :NEW.IdLugar, :NEW.IdCuenta);        
    END IF;
END;
