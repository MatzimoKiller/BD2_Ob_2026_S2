--==========================================--|
--Un lugar cerrado no admite nuevas reseñas --|> -R57
--==========================================--|
CREATE OR REPLACE TRIGGER trg_resenia_lugar_abierto
BEFORE INSERT OR UPDATE ON Resenia
FOR EACH ROW
DECLARE
    v_estado Lugar.Estado%TYPE;--Ponesmos %TYPE por si es que cambiamos el tipo de dato :P
    BEGIN
        SELECT Estado INTO v_estado
            FROM Lugar
        WHERE Identificador = :NEW.IdLugar;

    IF v_estado = 'CD' THEN
        RAISE_APPLICATION_ERROR(-20014,
            'El lugar ' || :NEW.IdLugar ||
            ' esta cerrado definitivamente y no admite reseñas');
    END IF;

    EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;   -- lugar inexistente
END;
/
--=============================================================--|
--Una categoria secundaria no puede ser igual que la principal --|> -R76
--=============================================================--|
CREATE OR REPLACE TRIGGER trg_categoria_sec_distinta_principal
BEFORE INSERT OR UPDATE ON Categoria_Secundaria
FOR EACH ROW
DECLARE
    v_nombre Lugar.Categoria_principal%TYPE;--Ponemos %TYPE por si es que cambiamos el tipo de dato :P
    BEGIN
        SELECT Categoria_principal INTO v_nombre
          FROM Lugar
        WHERE Identificador = :NEW.IdLugar;

        IF v_nombre = :NEW.NomCategoria THEN
            RAISE_APPLICATION_ERROR(-20015,
                'La categoría ' || :NEW.NomCategoria ||
                ' ya es principal, no puede ser secundaria');
        END IF;

    EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;   -- lugar inexistente
END;
